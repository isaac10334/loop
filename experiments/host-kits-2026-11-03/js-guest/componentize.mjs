const packageRoot=new URL('file:///C:/src/ilt/loop/experiments/wasip3/js/node_modules/@bytecodealliance/componentize-js/');
const manifest=JSON.parse(await readFile(new URL('package.json',packageRoot),'utf8'));
if(manifest.version!=='0.22.0')throw Error('Pinned ComponentizeJS0.22.0 unavailable');
